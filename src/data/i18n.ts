/**
 * Universal phrase & terminology translator for dynamic game content
 */
export function localizeText(text: string, lang: string = 'en'): string {
  if (!text || lang === 'en') return text;

  // Direct lookup
  const vocab = VOCABULARY_BY_LANG[lang];
  if (vocab && vocab[text]) return vocab[text];

  // If a language doesn't have a direct vocab table, check Spanish/French/German as reference or return text
  if (!vocab) return text;

  // Phrase replacement
  let res = text;
  for (const [enPhrase, transPhrase] of Object.entries(vocab)) {
    if (res.includes(enPhrase)) {
      res = res.replaceAll(enPhrase, transPhrase);
    }
  }

  return res;
}

/**
 * Localizes an entire scenario (title, description, options, survivor encounters)
 */
export function localizeScenario(scenario: Scenario, lang: string = 'en'): Scenario {
  if (lang === 'en') return scenario;

  const title = localizeText(scenario.title, lang);
  const desc = localizeText(scenario.desc, lang);

  const options = scenario.options.map(opt => {
    let optText = localizeText(opt.text, lang);
    return {
      ...opt,
      text: optText
    };
  });

  let survivorEncounter = scenario.survivorEncounter;
  if (survivorEncounter) {
    survivorEncounter = {
      ...survivorEncounter,
      role: localizeText(survivorEncounter.role, lang)
    };
  }

  return {
    ...scenario,
    title,
    desc,
    survivorEncounter,
    options
  };
}

/**
 * Localizes an inventory item
 */
export function localizeItem(item: InventoryItem, lang: string = 'en'): InventoryItem {
  if (lang === 'en') return item;
  return {
    ...item,
    name: localizeText(item.name, lang),
    desc: localizeText(item.desc, lang)
  };
}

/**
 * Localizes a map / sector
 */
export function localizeMap(map: MapData, lang: string = 'en'): MapData {
  if (lang === 'en') return map;
  return {
    ...map,
    name: localizeText(map.name, lang),
    desc: localizeText(map.desc, lang),
    hazards: map.hazards.map(h => localizeText(h, lang))
  };
}

/**
 * Localizes an entity dossier
 */
export function localizeEntity(entity: EntityInfo, lang: string = 'en'): EntityInfo {
  if (lang === 'en') return entity;
  return {
    ...entity,
    name: localizeText(entity.name, lang),
    entityRole: entity.entityRole ? localizeText(entity.entityRole, lang) : undefined,
    counter: localizeText(entity.counter, lang)
  };
}
